// The party is the pool of hero kinds a run can hire, not a battlefield formation. Changes stay in a draft until confirmed.
import { ALL_HEROES, UNITS } from './sim/units';
import { partySlots, saveMeta, setParty, type Meta } from './sim/meta';
import { progressOf, xpOf } from './sim/levels';
import { levelBadge } from './levelBadge';
import { countTraits, traitsOf } from './sim/traits';
import { traitBadge } from './traitBadge';
import { raisedBy } from './traitHelp';
import { portrait } from './render/sheets';
import { lockInfo } from './sim/contentHeroes';
import { drawHeroSheet, starsOf } from './menuHeroes';
import { kindPower, powerText } from './sim/power';
import { ROLE_NAMES, roleOf, suggestParty, type PartyRole } from './sim/suggest';

const $ = <T extends HTMLElement>(id: string) => document.getElementById(id) as T;
const el = <K extends keyof HTMLElementTagNameMap>(tag: K, cls = '', text = ''): HTMLElementTagNameMap[K] => {
  const e = document.createElement(tag);
  e.className = cls;
  e.textContent = text;
  return e;
};
const LONG_PRESS_MS = 450;
const FILTERS: [PartyRole | 'all', string][] = [['all', 'All'], ['front', 'Front-line'], ['striker', 'Striker'], ['back', 'Back-line'], ['support', 'Support']];

export class Party {
  private picked: string[] = [];
  private note = '';
  private held = false;
  private focus?: string;
  private query = '';
  private role: PartyRole | 'all' = 'all';
  private stopSheet: (() => void) | null = null;
  private sheetTrigger: HTMLElement | null = null;
  private returnFocus: HTMLElement | null = null;
  private onDone: () => void = () => {};

  constructor(
    private meta: Meta,
    private onBack: () => void,
  ) {
    $('ptBack').addEventListener('click', () => this.close(this.onBack));
    $('ptGo').addEventListener('click', () => this.confirm());
    $('ptSuggest').addEventListener('click', () => this.suggest());
    // Suppress the click generated by a long press, but never swallow the next deliberate selection.
    window.addEventListener('pointerup', () => window.setTimeout(() => { this.held = false; }, 0));
    window.addEventListener('pointercancel', () => { this.held = false; });
    $('ptSearch').addEventListener('input', () => {
      this.query = $<HTMLInputElement>('ptSearch').value;
      this.drawGrid(true);
    });
    for (const [id, name] of FILTERS) {
      const b = el('button', '', name);
      b.type = 'button';
      b.dataset.role = id;
      b.addEventListener('click', () => {
        this.role = id;
        this.drawFilters();
        this.drawGrid(true);
      });
      $('ptFilters').append(b);
    }
    $('ptSheet').addEventListener('click', e => { if (e.target === $('ptSheet')) this.closeSheet(); });
    $('party').addEventListener('keydown', e => {
      if (e.key === 'Escape') {
        e.preventDefault();
        if (!$('ptSheet').hidden) this.closeSheet();
        else this.close(this.onBack);
      }
      if (e.key !== 'Tab') return;
      const scope = !$('ptSheet').hidden ? $('ptSheet') : $('party');
      const items = [...scope.querySelectorAll<HTMLElement>('button:not(:disabled), input, [tabindex="0"]')].filter(x => x.getClientRects().length);
      if (!items.length) return;
      if (e.shiftKey && document.activeElement === items[0]) {
        e.preventDefault();
        items.at(-1)!.focus();
      } else if (!e.shiftKey && document.activeElement === items.at(-1)) {
        e.preventDefault();
        items[0].focus();
      }
    });
  }

  /** Existing callers can omit the optional expedition label; selection rules remain unchanged. */
  open(mode: 'start' | 'edit', then: () => void, context?: string): void {
    this.returnFocus = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    this.picked = [...this.meta.party];
    this.note = '';
    this.focus = undefined;
    this.query = '';
    this.role = 'all';
    this.held = false;
    this.onDone = then;
    $<HTMLInputElement>('ptSearch').value = '';
    $('ptContext').textContent = context ?? (mode === 'edit' ? 'Your next expedition' : 'Prepare your expedition');
    $('ptGo').textContent = mode === 'start' ? 'Start run' : 'Done';
    $('party').hidden = false;
    this.draw();
    $('ptBack').focus();
  }
  private get slots(): number {
    return partySlots(this.meta);
  }
  private confirm(): void {
    if (!setParty(this.meta, this.picked)) return;
    saveMeta(this.meta);
    this.close();
    this.onDone();
  }
  private close(then?: () => void): void {
    this.closeSheet();
    $('party').hidden = true;
    then?.();
    if (this.returnFocus?.isConnected && this.returnFocus.getClientRects().length) this.returnFocus.focus();
  }
  private suggest(): void {
    this.picked = suggestParty(this.meta.unlocked, this.slots, k => kindPower(this.meta, k));
    this.note = 'Suggested party ready. You can still change any hero.';
    this.draw();
  }
  private toggle(kind: string): void {
    if (this.picked.includes(kind)) {
      this.picked = this.picked.filter(k => k !== kind);
      this.note = '';
    } else if (this.picked.length < this.slots) {
      this.picked.push(kind);
      this.note = '';
    } else this.note = 'The party is full: take a hero out first.';
    this.draw();
  }
  private holdTo(card: HTMLElement, kind: string): void {
    let timer = 0;
    card.addEventListener('pointerdown', () => {
      this.held = false;
      timer = window.setTimeout(() => {
        this.held = true;
        this.openSheet(kind);
      }, LONG_PRESS_MS);
    });
    for (const end of ['pointerup', 'pointerleave', 'pointercancel']) card.addEventListener(end, () => clearTimeout(timer));
    card.addEventListener('contextmenu', e => e.preventDefault());
  }
  private openSheet(kind: string): void {
    this.closeSheet();
    this.sheetTrigger = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    $('ptSheet').hidden = false;
    this.stopSheet = drawHeroSheet($('ptSheetBox'), this.meta, kind, () => this.closeSheet());
    $('ptSheet').querySelector<HTMLElement>('button')?.focus();
  }
  private closeSheet(): void {
    this.stopSheet?.();
    this.stopSheet = null;
    $('ptSheet').hidden = true;
    if (this.sheetTrigger?.isConnected) this.sheetTrigger.focus();
    this.sheetTrigger = null;
  }
  private drawFilters(): void {
    for (const b of $('ptFilters').querySelectorAll('button')) b.setAttribute('aria-pressed', String(b.dataset.role === this.role));
  }
  private draw(): void {
    const active = document.activeElement instanceof HTMLElement ? document.activeElement.dataset.partyFocus : undefined;
    $('ptCount').textContent = `${this.picked.length} / ${this.slots}`;
    const row = $('ptSlots');
    row.replaceChildren();
    row.style.setProperty('--party-slots', String(Math.max(1, this.slots)));
    for (let i = 0; i < this.slots; i++) {
      const kind = this.picked[i];
      if (!kind) { const empty = el('div', 'ptSlot empty'); empty.append(el('span', '', '+'), el('small', '', 'Choose hero')); row.append(empty); continue; }
      const b = el('button', 'ptSlot');
      b.type = 'button';
      b.dataset.partyFocus = `slot-${kind}`;
      b.dataset.kind = kind;
      b.setAttribute('aria-label', `Remove ${UNITS[kind].name} from party`);
      b.append(portrait(UNITS[kind].sheet, 64), el('small', '', UNITS[kind].name), el('span', 'ptRemove', '×'));
      b.addEventListener('click', () => this.held ? (this.held = false) : this.toggle(kind)); this.holdTo(b, kind);
      row.append(b);
    }
    const roles = this.picked.map(roleOf);
    const coverage = $('ptRoles');
    coverage.replaceChildren();
    for (const [label, count] of [['Front-line', roles.filter(r => r === 'front').length], ['Damage', roles.filter(r => r === 'striker' || r === 'back').length], ['Support', roles.filter(r => r === 'support').length]] as const) {
      const b = el('span', `ptRole${count ? ' present' : ''}`); b.append(el('b', '', String(count)), el('span', '', label)); coverage.append(b);
    }
    const traits = $('ptTraits');
    traits.replaceChildren();
    const counts = countTraits(this.picked).sort((a, b) => Number(b.active) - Number(a.active));
    // Removing the last contributor also removes its summary badge, so its filter must not linger invisibly.
    if (this.focus && !counts.some(c => c.trait.id === this.focus)) this.focus = undefined;
    $('ptTraitTitle').textContent = `Traits · ${counts.filter(c => c.active).length} active`;
    for (const c of counts) {
      const next = c.trait.tiers[Math.min(c.trait.tiers.length - 1, c.tier + 1)];
      const effect = c.active ? c.trait.tiers[c.tier].text : next.text;
      const b = el('button', `ptTrait${c.active ? ' on' : ''}`);
      b.type = 'button';
      b.dataset.partyFocus = `trait-${c.trait.id}`;
      b.dataset.trait = c.trait.id;
      b.setAttribute('aria-pressed', String(this.focus === c.trait.id));
      b.setAttribute('aria-label', `${c.trait.name}, ${c.count} of ${c.goal}, ${c.active ? 'active' : 'next tier'}: ${effect}`); b.title = effect;
      b.append(traitBadge(c.trait.id, { small: true, lit: this.focus === c.trait.id }), el('span', '', `${c.trait.name} ${c.count}/${c.goal}`));
      b.addEventListener('click', () => { this.focus = this.focus === c.trait.id ? undefined : c.trait.id; this.draw(); }); traits.append(b);
    }
    if (!counts.length) traits.append(el('span', 'ptMuted', 'Choose heroes to discover traits'));
    const match = counts.find(c => c.trait.id === this.focus);
    $('ptTraitHint').classList.toggle('is-focused', !!match);
    $('ptTraitHint').textContent = match ? `${match.trait.name}: ${match.active ? match.trait.tiers[match.tier].text : match.trait.tiers[Math.min(match.trait.tiers.length - 1, match.tier + 1)].text} · tap again to clear` : 'Tap a trait to find matching heroes';
    const full = this.picked.length === this.slots;
    $('ptHint').textContent = this.note || (full ? 'Your party is ready' : `Choose ${this.slots - this.picked.length} more ${this.slots - this.picked.length === 1 ? 'hero' : 'heroes'}`);
    $('ptHint').classList.toggle('full', !!this.note && !full || this.note.startsWith('The party is full'));
    $<HTMLButtonElement>('ptGo').disabled = !full;
    this.drawFilters();
    this.drawGrid();
    if (active) ($('party').querySelector<HTMLElement>(`[data-party-focus="${CSS.escape(active)}"]`) ?? $('ptSearch')).focus({ preventScroll: true });
  }
  private drawGrid(resetScroll = false): void {
    const grid = $('ptGrid');
    const scroll = resetScroll ? 0 : grid.scrollTop;
    grid.replaceChildren();
    const q = this.query.trim().toLocaleLowerCase('en-GB');
    const order = [...ALL_HEROES].sort((a, b) => Number(this.meta.unlocked.includes(b)) - Number(this.meta.unlocked.includes(a)));
    let count = 0;
    for (const kind of order) {
      const def = UNITS[kind];
      const open = this.meta.unlocked.includes(kind);
      const lock = lockInfo(this.meta, kind);
      const name = open || lock?.named ? def.name : '???';
      if ((q && !name.toLocaleLowerCase('en-GB').includes(q)) || (this.role !== 'all' && roleOf(kind) !== this.role)) continue;
      const on = this.picked.includes(kind), hit = !!this.focus && traitsOf(kind).includes(this.focus);
      const wrap = el('div', `ptCard${open ? '' : ' locked'}${on ? ' picked' : ''}${hit ? ' hit' : ''}${this.focus && !hit ? ' faded' : ''}`);
      wrap.dataset.kind = kind;
      wrap.dataset.role = roleOf(kind);
      const card = el('button', 'ptSelect');
      card.type = 'button';
      card.dataset.partyFocus = `hero-${kind}`;
      card.setAttribute('aria-label', open ? `${on ? 'Remove' : 'Add'} ${def.name}${on ? ' from' : ' to'} party` : `Unlock requirements for ${name}`);
      if (open) card.setAttribute('aria-pressed', String(on));
      const art = el('span', `ptPortrait role-${roleOf(kind)}`);
      art.append(portrait(def.sheet, 112));
      if (on) art.append(el('span', 'ptCheck', '✓')); else if (!open) art.append(el('span', 'ptCheck', '🔒'));
      card.append(art, el('b', 'ptName', name));
      if (open) {
        card.append(levelBadge(progressOf(xpOf(this.meta, kind)).level));
        // Existing rank, power and trait details remain available without crowding the portrait cards.
        card.title = `${def.name} · ${ROLE_NAMES[roleOf(kind)]} · ${starsOf(this.meta, kind)} · Power ${powerText(kindPower(this.meta, kind))}`;
      } else card.append(el('span', 'ptLock', lock!.short));
      card.addEventListener('click', () => open ? (this.held ? (this.held = false) : this.toggle(kind)) : this.openSheet(kind));
      if (open) this.holdTo(card, kind);
      wrap.append(card);
      const info = el('button', 'ptInfo', 'i');
      info.type = 'button';
      info.setAttribute('aria-label', `Details for ${name}`);
      info.dataset.partyFocus = `info-${kind}`;
      info.addEventListener('click', () => this.openSheet(kind));
      wrap.append(info);
      if (open && this.focus && hit && raisedBy(this.picked, kind).includes(this.focus)) wrap.append(el('span', 'ptRaises', '+ Trait'));
      grid.append(wrap);
      count++;
    }
    $('ptResults').textContent = `${count} ${count === 1 ? 'hero' : 'heroes'}`;
    if (!count) { const empty = el('div', 'ptEmpty'); empty.append(el('b', '', 'No heroes found'), el('span', '', 'Try another name or role filter.')); grid.append(empty); }
    grid.scrollTop = scroll;
  }
}
