// Wire only artwork into the current unit definitions, retaining all combat
// values and role descriptions. Safe to repeat after rear/walk packing.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { sheetOf } = require('./atlas.cjs');
const specs = require('./roster.json'), variants = require('./variants.json');
const layout = require('../../src/art/units/sheets.json');
let units = fs.readFileSync('src/sim/units.ts', 'utf8');
for (const s of specs) {
  const sheet = sheetOf(s.id);
  assert.ok(layout[sheet] && fs.existsSync(`src/art/units/${sheet}.png`), `Missing ${sheet}`);
  const pattern = new RegExp(`^  ${s.id}: \\{[^\\n]+`, 'm'), original = units.match(pattern)?.[0];
  assert.ok(original, s.id);
  const forms = original.includes('forms:');
  let line = original.replace(/sheet: '[^']+'/, `sheet: '${sheet}'`).replace(/scale: [\d.]+/, `scale: ${Number((s.size / layout[sheet].figure).toFixed(6))}`)
    .replace(/, forms: \[[^\]]+\]/, '');
  if (forms) {
    const third = s.id === 'werewolf' ? sheetOf('werewolfBrute') : sheet;
    line = line.replace(/ \},$/, `, forms: ['${sheet}', '${sheet}', '${third}'] },`);
  }
  units = units.replace(original, line);
}
for (const [id, sheet, scale, forms] of [
  ['treant', sheetOf('treant'), 0.5, [sheetOf('treant'), sheetOf('treant2'), sheetOf('treant3')]],
  ['decoy', sheetOf('illusionist'), 42 / 96, null],
]) {
  const pattern = new RegExp(`^  ${id}: \\{[^\\n]+`, 'm'), original = units.match(pattern)?.[0];
  assert.ok(original, id);
  let line = original.replace(/sheet: '[^']+'/, `sheet: '${sheet}'`).replace(/scale: [\d.]+/, `scale: ${scale}`).replace(/, forms: \[[^\]]+\]/, '');
  if (forms) line = line.replace(/ \},$/, `, forms: [${forms.map(s => `'${s}'`).join(', ')}] },`);
  units = units.replace(original, line);
}
fs.writeFileSync('src/sim/units.ts', units);
const fronts = ['hero_soldier', 'hero_samurai_archer', ...specs.map(s => sheetOf(s.id)), ...variants.map(s => sheetOf(s.id))];
const ids = [...fronts, ...fronts.flatMap(id => layout[id]?.rear ? [layout[id].rear] : [])];
const source = '// Generated by tools/resonance/apply.cjs from the packed hero sheets.\n' +
  ids.map((id, i) => `import art${i} from '../art/units/${id}.png';`).join('\n') +
  '\n\nexport const RESONANCE_URLS: Record<string, string> = {\n' + ids.map((id, i) => `  ${id}: art${i},`).join('\n') + '\n};\n';
fs.writeFileSync('src/render/resonanceArt.ts', source);
let sheets = fs.readFileSync('src/render/sheets.ts', 'utf8');
if (!sheets.includes("import { RESONANCE_URLS }")) {
  sheets = sheets.replace("import layout from '../art/units/sheets.json';", "import layout from '../art/units/sheets.json';\nimport { RESONANCE_URLS } from './resonanceArt';");
  sheets = sheets.replace("import resonanceSoldier from '../art/units/hero_soldier.png';\n", '').replace("import resonanceArcher from '../art/units/hero_samurai_archer.png';\n", '');
  sheets = sheets.replace('  hero_soldier: resonanceSoldier,\n', '').replace('  hero_samurai_archer: resonanceArcher,\n', '');
  sheets = sheets.replace('const URLS: Record<string, string> = {', 'const URLS: Record<string, string> = {\n  ...RESONANCE_URLS,');
}
fs.writeFileSync('src/render/sheets.ts', sheets);
console.log(`Registered ${fronts.length} front sheets and ${ids.length - fronts.length} rear sheets; combat definitions retained.`);
