def half(im):
    a = np.array(im.convert('RGBA')).astype(float)
    h, w = a.shape[0] // 2, a.shape[1] // 2
    a = a[:h * 2, :w * 2].reshape(h, 2, w, 2, 4)
    al = a[..., 3].sum(axis=(1, 3))
    rgb = (a[..., :3] * a[..., 3:4]).sum(axis=(1, 3)) / np.maximum(al, 1)[..., None]
    out = np.zeros((h, w, 4), np.uint8)
    out[..., :3] = rgb.clip(0, 255)
    out[..., 3] = np.where(al >= 510, 255, 0)
    return Image.fromarray(out)


sprites = {}
for name, path in PIECES.items():
    im = Image.open(os.path.join(KITS, path + '.png'))
    # (the small flair is kept at its own size: halved, a flower is a pixel)
    im = im.convert('RGBA') if min(im.size) < 70 else half(im)
    sprites[name] = im.crop(im.getchannel('A').getbbox())

order = sorted(sprites, key=lambda k: (-sprites[k].height, k))
W = 1024
x = y = rowh = 0
rects = {}
for k in order:
    im = sprites[k]
    if x + im.width + 1 > W:
        x, y, rowh = 0, y + rowh + 1, 0
    rects[k] = [x, y, im.width, im.height]
    x += im.width + 1
    rowh = max(rowh, im.height)
H = y + rowh
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for k, (rx, ry, rw, rh) in rects.items():
    atlas.alpha_composite(sprites[k], (rx, ry))
out = os.path.join(ROOT, 'src', 'art', 'road')
os.makedirs(out, exist_ok=True)
atlas.quantize(256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(os.path.join(out, 'atlas.png'), optimize=True)
with open(os.path.join(ROOT, 'src', 'render', 'roadAtlas.ts'), 'w') as f:
    f.write('// Where each of the army road\'s pieces sits in src/art/road/atlas.png ([x, y, w, h]).\n')
    f.write('// GENERATED by tools/army-road/prep.py: do not edit by hand.\n\n')
    f.write(f'export const ROAD_ATLAS_SIZE: [number, number] = [{W}, {H}];\n')
    f.write('export const ROAD_RECTS: Record<string, [number, number, number, number]> = ' + json.dumps({k: rects[k] for k in sorted(rects)}, indent=1).replace('"', "'") + ';\n')
print('atlas', W, H, len(sprites), os.path.getsize(os.path.join(out, 'atlas.png')))
