"""EMIT-POINTS (docs/notes/emit-points.md): a weapon's reach, read off every fighter's sheet, written to src/render/reachData.ts.

A melee blow lands at the wind-up's end (0.4 of the attack, 400 ms at most) of a swing 250 ms longer, so the frame on show as it
lands is about six tenths of the way through the attack row. On that frame the figure's reach is the forward-most thing drawn:
the weapon's end, a claw, a horn. Its place is the forward-most drawn column and the middle height of what is drawn in the last
REACH_BAND px before it, in the sheet's pixels from the middle of the frame's bottom edge (x towards the way the figure faces, y
up). A sheet drawn facing left is read mirrored. A sheet with a look from behind has that read too.

  python3 tools/emit-points/reach.py            write the table
  python3 tools/emit-points/reach.py out.png    and draw every frame with its point (a sheet of them, for looking over)
"""
import json, os, sys
from PIL import Image, ImageDraw

SHARE, REACH_BAND = 0.6, 4
d = json.load(open('src/art/units/sheets.json'))


def strike(k):
    L = d[k]
    path = f'src/art/units/{k}.png'
    if 'attack' not in L['rows'] or not L['counts'].get('attack') or not os.path.exists(path):
        return None
    im = Image.open(path).convert('RGBA')
    r = L['rows'].index('attack')
    start = sum(-(-L['counts'][x] // L['perRow']) for x in L['rows'][:r])
    i = min(L['counts']['attack'] - 1, int(SHARE * L['counts']['attack']))
    fr = im.crop(((i % L['perRow']) * L['w'], (start + i // L['perRow']) * L['h'], (i % L['perRow'] + 1) * L['w'], (start + i // L['perRow'] + 1) * L['h']))
    if L.get('facesRight') is False:
        fr = fr.transpose(Image.FLIP_LEFT_RIGHT)
    px = fr.load()
    cols = [x for x in range(L['w']) if any(px[x, y][3] > 128 for y in range(L['h']))]
    if not cols:
        return None
    far = max(cols)
    ys = sorted(y for x in range(max(0, far - REACH_BAND + 1), far + 1) for y in range(L['h']) if px[x, y][3] > 128)
    return fr, L, far - L['w'] // 2, L['h'] - 1 - ys[len(ys) // 2], i


out, cells = {}, []
rears = {L['rear'] for L in d.values() if L.get('rear')}
for k in sorted(d):
    if k in rears:
        continue
    f = strike(k)
    if not f:
        continue
    e = {'front': [f[2], f[3]]}
    cells.append((f, k))
    b = strike(d[k]['rear']) if d[k].get('rear') else None
    if b:
        e['back'] = [b[2], b[3]]
        cells.append((b, k + ' (rear)'))
    out[k] = e
rows = '\n'.join(f"  {k}: {{ front: [{e['front'][0]}, {e['front'][1]}]" + (f", back: [{e['back'][0]}, {e['back'][1]}]" if 'back' in e else '') + ' },' for k, e in out.items())
open('src/render/reachData.ts', 'w').write(f'''// EMIT-POINTS: generated by tools/emit-points/reach.py from the fighters' sheets. Do not edit by hand.
// A weapon's reach on the frame on show as a melee blow lands: the forward-most thing drawn, in the sheet's pixels from the middle of
// the frame's bottom edge (x towards the way the figure faces, y up), for the look from the front and, where a sheet has one, from behind.
export const REACH: Readonly<Record<string, {{ front: readonly [number, number]; back?: readonly [number, number] }}>> = {{
{rows}
}};
''')
print(len(out), 'sheets;', sum('back' in e for e in out.values()), 'with a look from behind')
if len(sys.argv) > 1:
    Z, per = 2, 10
    W = max(c[0][1]['w'] for c in cells) * Z
    H = max(c[0][1]['h'] for c in cells) * Z
    sh = Image.new('RGB', (W * per, H * -(-len(cells) // per)), (40, 46, 56))
    dr = ImageDraw.Draw(sh)
    for n, ((fr, L, x, y, i), name) in enumerate(cells):
        ox, oy = (n % per) * W, (n // per) * H
        big = fr.resize((L['w'] * Z, L['h'] * Z), Image.NEAREST)
        sh.paste(big, (ox, oy), big)
        cx, cy = ox + (L['w'] // 2 + x) * Z, oy + (L['h'] - 1 - y) * Z
        dr.line([(cx - 8, cy), (cx + 8, cy)], fill=(0, 255, 255))
        dr.line([(cx, cy - 8), (cx, cy + 8)], fill=(0, 255, 255))
        dr.text((ox + 2, oy + 2), name[:26], fill=(255, 230, 120))
    sh.save(sys.argv[1])
