"""SUMMON-SMOOTH (docs/notes/summon-smooth.md): each unit sheet's idle box, found once here and not on the phone.

    python3 tools/summon-smooth/idle-boxes.py            write src/render/idleBoxData.ts
    python3 tools/summon-smooth/idle-boxes.py --check    fail if the table is not what the sheets give

The game finds where a sheet's idle figure lies in its frame (the box round every drawn pixel of every idle frame) to cut a
portrait or a whole figure from it. It did so on the page, by drawing the sheet's idle row to a canvas and reading its pixels back:
for every sheet a card or a menu showed, and for all of them in the background after the page loads (`warmPortraits`). On a
throttled phone that was most of the time a ten-stone draw's cards took to come up. The boxes are the art's own: this finds them the
same way (alpha over 8, the idle row as the page reads it) and writes them with each sheet's size in bytes, so a test fails when a
sheet is changed and the table is not made again. A sheet that is not found here keeps the page's own reading.
"""
import glob, json, os, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'render', 'idleBoxData.ts')
layout = json.load(open(os.path.join(ROOT, 'src', 'art', 'units', 'sheets.json')))
found = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'src', 'art', '**', '*.png'), recursive=True)):
    found.setdefault(os.path.splitext(os.path.basename(path))[0], []).append(path)

rows = {}
for name, l in sorted(layout.items()):
    paths = found.get(name, [])
    # (only a sheet with one file of its name: where two folders hold the name, the page's own reading stays)
    if len(paths) != 1:
        continue
    im = Image.open(paths[0]).convert('RGBA')
    w, h = l['w'], l['h']
    row = max(0, l['rows'].index('idle')) if 'idle' in l['rows'] else 0
    count = l['counts'].get('idle', 1)
    strip = Image.new('RGBA', (w * count, h), (0, 0, 0, 0))
    strip.paste(im.crop((0, row * h, w * count, row * h + h)), (0, 0))
    a = strip.getchannel('A').point(lambda v: 255 if v > 8 else 0)
    x0, y0, x1, y1 = w, h, -1, -1
    for i in range(count):
        box = a.crop((i * w, 0, (i + 1) * w, h)).getbbox()
        if box:
            x0, y0, x1, y1 = min(x0, box[0]), min(y0, box[1]), max(x1, box[2] - 1), max(y1, box[3] - 1)
    b = [0, 0, w, h] if x1 < 0 else [x0, y0, x1 - x0 + 1, y1 - y0 + 1]
    rows[name] = b + [os.path.getsize(paths[0]), os.path.relpath(paths[0], ROOT)]

body = ('// GENERATED by tools/summon-smooth/idle-boxes.py: do not edit. Each unit sheet\'s idle box (the box round every drawn pixel of its\n'
        '// idle frames: x, y, w, h in the frame), found once from the art, with the sheet\'s size in bytes and its file (a test fails when a\n'
        '// sheet changes and this is not made again). `sheets.ts` reads it in place of reading the sheet\'s pixels back on the phone.\n\n'
        'export const IDLE_BOX: Readonly<Record<string, readonly [number, number, number, number, number, string]>> = {\n'
        + ''.join(f"  {json.dumps(k)}: {json.dumps(v)},\n" for k, v in rows.items()) + '};\n')
if '--check' in sys.argv:
    if open(OUT).read() != body:
        raise SystemExit('src/render/idleBoxData.ts is stale: run python3 tools/summon-smooth/idle-boxes.py')
    print('up to date')
else:
    open(OUT, 'w').write(body)
    print(f'{len(rows)} of {len(layout)} sheets; {os.path.getsize(OUT)} bytes')
