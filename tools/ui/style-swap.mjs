// Writes src/styles/swap.css: a copy of every rule that draws a UI picture (url(ui/<name>.png)) from pixel.css and rogue.css, scoped
// under body[data-style] and reading the picture from a variable (var(--u-<name>)) that each style sets to its own file. So a style
// changes the frames and the wood by naming new files; today's look (no data-style) is untouched. Run: node tools/ui/style-swap.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const KEEP = /url\(ui\/(?!ic-|tab-|chest-)([a-z0-9-]+)\.png\)/g;
const used = new Set();
// colours that a style needs to change inside the copied rules become variables whose defaults are today's values
const COLOURS = [['url(ui/wood.png) 0 0 / 32px 32px, #1c1008', 'var(--u-page) 0 0 / 32px 32px, var(--page-bg)'], ['#4a1a06', 'var(--btn-ink)'], ['rgba(255, 228, 138, 0.7)', 'var(--btn-glow)'], ['#8a7c6c', 'var(--off-ink)'], ['#f0b0a0', 'var(--lost-ink)']];
const STYLE_KEYS = ['a', 'b', 'c', 'd'];
/** Rules of a stylesheet, with @media blocks kept whole. */
function rules(css) {
  const out = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let depth = 1, j = open + 1;
    while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    out.push({ head: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}
const strip = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');
function swap(rs) {
  const lines = [];
  for (const r of rs) {
    if (r.head.startsWith('@media')) { const inner = swap(rules(r.body)); if (inner.length) lines.push(`${r.head} {\n${inner.join('\n')}\n}`); continue; }
    if (r.head.startsWith('@')) continue;
    if (!KEEP.test(r.body)) { KEEP.lastIndex = 0; continue; }
    KEEP.lastIndex = 0;
    // (only the declarations that draw a picture or use a mapped colour: copying a whole rule would win over later, lower rules)
    const mapped = COLOURS.reduce((t, [from, to]) => t.split(from).join(to), r.body).replace(KEEP, (_, n) => (used.add(n), `var(--u-${n})`));
    const body = mapped.split(';').map((d) => d.trim()).filter((d) => /var\(--(u-|btn-|off-|lost-)/.test(d)).join('; ');
    if (!body) continue;
    const sel = r.head.split(',').map((s) => `body[data-style] ${s.trim().replace(/^body /, '')}`).join(', ');
    lines.push(`${sel} { ${body.replace(/\s*\n\s*/g, ' ')}; }`);
  }
  return lines;
}
let all = [];
for (const f of ['src/pixel.css', 'src/rogue.css']) all = all.concat(swap(rules(strip(readFileSync(f, 'utf8')))));
// the inline rules in index.html and starter.ts that draw a picture too
const html = strip(readFileSync('src/index.html', 'utf8'));
all = all.concat(swap(rules(html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>')))));
const head = `/* GENERATED by tools/ui/style-swap.mjs: the rules that draw a UI picture, repeated under body[data-style] with the picture read from --u-<name>.\n   Pictures used: ${[...used].sort().join(', ')}. Do not edit by hand. */\n`;
// each style's file names, as variables on the body
const vars = STYLE_KEYS.map((k) => `body[data-style='${k}'] { ${[...used].sort().map((n) => `--u-${n}: url(ui/styles/${k}/${n}.png);`).join(' ')} --u-page: url(ui/styles/${k}/page.png); }`).join('\n');
writeFileSync('src/styles/swap.css', head + vars + '\n' + all.join('\n') + '\n');
console.log(`${all.length} rules, ${used.size} pictures: ${[...used].sort().join(' ')}`);
