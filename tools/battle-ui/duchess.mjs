import { serve, launch, boot } from './lib.mjs';
const s = serve();
const br = await launch();
const { page, errors } = await boot(br, 393, 852);
await page.goto('http://localhost:8139/?seed=5');
await page.waitForTimeout(2500);
const vis = () => page.evaluate(() => { const r = document.querySelector('.duchess'); return { visibility: r.style.visibility, left: r.style.left, hidden: r.hidden }; });
await page.evaluate(() => { const gt = window.__game.goat; gt.plan = null; gt.planned = true; });
console.log('no visit:', JSON.stringify(await vis()));
await page.evaluate(() => { const gt = window.__game.goat; gt.plan = { arrive: 500, stay: 6000 }; gt.planAt = performance.now(); });
await page.waitForTimeout(2200);
console.log('walking in:', JSON.stringify(await vis()));
await page.screenshot({ path: 'docs/samples/battle-ui-duchess-in.png', clip: { x: 0, y: 560, width: 393, height: 92 } });
await page.waitForTimeout(3000);
console.log('here:', JSON.stringify(await vis()));
await page.screenshot({ path: 'docs/samples/battle-ui-duchess-here.png', clip: { x: 0, y: 560, width: 393, height: 92 } });
await page.waitForTimeout(8500);
console.log('gone:', JSON.stringify(await vis()), errors.length);
await br.close(); s.close();
